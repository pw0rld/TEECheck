package planner

import (
	"fmt"

	"github.com/pw0rld/TEECheck/tee-usage-scanner/internal/artifacts"
	"github.com/pw0rld/TEECheck/tee-usage-scanner/internal/config"
	"github.com/pw0rld/TEECheck/tee-usage-scanner/internal/runfs"
)

// WriteHotspotShim converts a planner evidence bundle into the legacy
// HotspotIndex and RepoMap file shapes so the existing cases.Run ->
// expert.Run -> challenger.Run -> verifier.RunWithBus -> arbiter.RunWithBus
// chain can consume the L3 planner's output without code changes.
//
// This is the bridge between the L3 planner and the pre-M4 audit
// pipeline. After M4 (pipeline.Run dispatches to planner when
// cfg.Mode == "llm"), every LLM-mode run goes through this shim.
//
// The shim writes two files:
//   - runDir/02_hotspots/hotspot_index.json — one hotspot per candidate
//   - runDir/01_repo_map/repo_map.json       — minimal repo_map so
//                                              cases.Run does not error
//     out when it reads the map for enrichment
//
// Requires cfg.RunDir to be set.
func WriteHotspotShim(cfg config.Config, bundle *artifacts.EvidenceBundle) error {
	if bundle == nil {
		return fmt.Errorf("WriteHotspotShim: bundle is nil")
	}
	hotspots := make([]artifacts.Hotspot, 0, len(bundle.Candidates))
	for i, c := range bundle.Candidates {
		hid := c.ID
		if hid == "" {
			hid = fmt.Sprintf("hotspot-%03d", i+1)
		}
		hotspots = append(hotspots, artifacts.Hotspot{
			HotspotID:   hid,
			Kind:        c.Kind,
			Priority:    c.Priority,
			Paths:       c.Paths,
			Symbols:     c.Symbols,
			WhySelected: c.WhySelected,
		})
	}
	index := artifacts.HotspotIndex{
		SchemaVersion: "teecheck.hotspot_index.v1",
		RunID:         bundle.RunID,
		Hotspots:      hotspots,
	}
	if err := runfs.WriteJSON(runfs.HotspotIndexPath(cfg.RunDir), index); err != nil {
		return fmt.Errorf("write hotspot_index shim: %w", err)
	}
	// cases.Run requires repo_map.json even if empty; collectToolFacts
	// iterates Boundaries which safely no-ops on an empty slice.
	repoMap := artifacts.RepoMap{
		SchemaVersion: "teecheck.repo_map.v1",
		Repo:          bundle.Repo,
		Notes: []string{
			"repo_map shim generated by planner.WriteHotspotShim; L3 planner provides candidates directly.",
		},
	}
	if err := runfs.WriteJSON(runfs.RepoMapPath(cfg.RunDir), repoMap); err != nil {
		return fmt.Errorf("write repo_map shim: %w", err)
	}
	return nil
}
