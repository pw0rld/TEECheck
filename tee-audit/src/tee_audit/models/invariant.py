"""Invariant data model — output of Stage 2."""

from __future__ import annotations

from enum import Enum

from pydantic import BaseModel

from tee_audit.models.finding import TaxonomyCategory


class InvariantFamily(str, Enum):
    """Analysis families for TEE×Web3 invariants."""

    FLOW = "Flow"
    GUARD = "Guard"
    BINDING = "Binding"
    STATE = "State"
    CONFIG = "Config"
    DESIGN = "Design"
    LEAKAGE = "Leakage"


class TaintSpec(BaseModel):
    """A taint specification for CodeQL — source/sink/sanitizer triple.

    Generated by LLM from TEE API understanding (IRIS-style).
    """

    source: str  # Function/pattern where tainted data originates
    sink: str  # Function/pattern where tainted data must not reach unchecked
    sanitizer: str | None = None  # Function/pattern that cleanses the taint
    taint_type: str = "data_flow"  # "data_flow" or "control_flow"
    description: str = ""  # Brief explanation of the taint flow


class Invariant(BaseModel):
    """A security invariant extracted from the repository's trust architecture."""

    id: str  # e.g., "INV-01"
    description: str
    trust_path: str
    family: InvariantFamily
    sources: list[str]
    sinks: list[str]
    guards: list[str]
    failure_modes: list[str]
    codeql_expressible: bool
    tee_dimension: str | None = None  # "incorrect_usage" or "inappropriate_design"
    tee_interaction: str = ""  # specific TEE primitive or trust boundary interaction
    taint_specs: list[TaintSpec] = []  # LLM-mined taint specifications for CodeQL


_FAMILY_TO_TAXONOMY = {
    InvariantFamily.FLOW: TaxonomyCategory.TRUST_BOUNDARY_FLOW,
    InvariantFamily.GUARD: TaxonomyCategory.VERIFICATION_GAP,
    InvariantFamily.BINDING: TaxonomyCategory.BINDING_WEAKNESS,
    InvariantFamily.STATE: TaxonomyCategory.STATE_CONTINUITY,
    InvariantFamily.CONFIG: TaxonomyCategory.CONFIGURATION_INTEGRITY,
    InvariantFamily.DESIGN: TaxonomyCategory.DESIGN_APPROPRIATENESS,
    InvariantFamily.LEAKAGE: TaxonomyCategory.OUTPUT_METADATA_LEAKAGE,
}


def family_to_taxonomy(family: InvariantFamily) -> TaxonomyCategory:
    """Map an InvariantFamily to its TaxonomyCategory equivalent."""
    return _FAMILY_TO_TAXONOMY[family]
